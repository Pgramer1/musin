# Report tables (tables/report/<name>.md|.tex) by name prefix -> section.
REPORT_TABLE_SECTIONS = (
    ("data_", "Data and ETL"),
    ("graph_", "Graph build"),
    ("rq1_", "RQ1 — genre bridges"),
    ("rq2_", "RQ2 — communities"),
    ("rq3_", "RQ3 — trends by decade"),
    ("rq4_", "RQ4 — centrality"),
    ("separation", "Degrees of separation"),
    ("sensitivity", "Sensitivity variants"),
    ("bench_", "Benchmarks"),
)


def _feature_key(feature: str) -> tuple[int, ...]:
    """'F4.10' sorts after 'F4.9'."""
    return tuple(int(x) for x in feature[1:].split("."))


def classify(rel: str) -> tuple[str, str, str] | None:
    """(section, feature, description) of a path relative to reports/, or None."""
    for pattern, section, feature, what in CATALOGUE:
        if fnmatch.fnmatch(rel, pattern):
            return section, feature, what
    return None


def report_table_section(name: str) -> str:
    for prefix, section in REPORT_TABLE_SECTIONS:
        if name.startswith(prefix):
            return section
    raise ValueError(f"report table {name!r} has no section prefix")


def render(reports: Path, report_tables: list[ReportTable]) -> tuple[str, list[str]]:
    """Markdown of reports/README.md and the list of files that matched no entry."""
    rows: dict[str, list[str]] = {s: [] for s in SECTIONS}
    unlisted: list[str] = []
    used: set[str] = set()
    files = sorted(
        p.relative_to(reports).as_posix()
        for p in reports.rglob("*")
        if p.is_file() and p.suffix in {".csv", ".png"}
    )
    for rel in files:
        hit = classify(rel)
        if hit is None:
            unlisted.append(rel)
            continue
        section, feature, what = hit
        used.add(feature)
        rows[section].append(f"| [`{rel}`]({rel}) | {what} | {feature} |")
    for t in report_tables:
        used.add("F6.1")
        rows[report_table_section(t.name)].append(
            f"| [`tables/report/{t.name}.md`](tables/report/{t.name}.md) · "
            f"[`.tex`](tables/report/{t.name}.tex) | {t.caption} | F6.1 |"
        )

    lines = [
        "# Report figures and tables",
        "",
        f"Generated by `{GENERATED_BY}` (F6.1, FR-24). Do not edit by hand.",
        "",
        "Every file below is written by code. The **Feature** column names the stage that "
        "writes it; the commands are at the end. Numbers in the report come from these files "
        "only (RULES §9). Main-graph files describe the post-G1 graph `full`; files under "
        "`variants/<name>/` describe the sensitivity graphs (F4.7). `tables/report/` holds "
        "report-ready versions (rounded, selected columns) of the CSVs, in Markdown and LaTeX.",
        "",
    ]
    for section in SECTIONS:
        if not rows[section]:
            continue
        lines += [
            f"## {section}",
            "",
            "| File | Shows | Feature |",
            "|---|---|---|",
            *rows[section],
            "",
        ]
    if unlisted:
        lines += [
            "## Not catalogued",
            "",
            "No entry in `musin.report.manifest.CATALOGUE`:",
            "",
            *[f"- `{u}`" for u in unlisted],
            "",
        ]
    lines += [
        "## Commands",
        "",
        "| Feature | Command |",
        "|---|---|",
        *[f"| {f} | `{COMMANDS[f]}` |" for f in sorted(used, key=_feature_key)],
        "",
    ]
    return "\n".join(lines), unlisted
