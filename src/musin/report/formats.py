"""Report tables as Markdown and LaTeX (F6.1, FR-24).

A ReportTable holds already formatted cell strings, so both outputs show
exactly the same numbers. The writers add a header naming the source table and
the generating command, because a report number must come from a generated
file, never be typed by hand (RULES §9).
"""

from __future__ import annotations

import math
from dataclasses import dataclass, field
from pathlib import Path

GENERATED_BY = "python -m musin.report --config config/pipeline.yaml"

_LATEX_ESCAPES = {
    "\\": r"\textbackslash{}",
    "&": r"\&",
    "%": r"\%",
    "$": r"\$",
    "#": r"\#",
    "_": r"\_",
    "{": r"\{",
    "}": r"\}",
    "~": r"\textasciitilde{}",
    "^": r"\textasciicircum{}",
}


@dataclass
class ReportTable:
    """One report table.

    name: file stem under reports/tables/report/ and LaTeX label suffix.
    columns: header labels; align: one of 'l', 'r', 'c' per column.
    rows: formatted cell strings; sources: the reports/tables CSVs it reads.
    notes: sentences shown under the table (Markdown) or in the caption (LaTeX).
    """

    name: str
    caption: str
    columns: list[str]
    align: str
    rows: list[list[str]]
    sources: list[str]
    notes: list[str] = field(default_factory=list)

    def __post_init__(self) -> None:
        if len(self.align) != len(self.columns):
            raise ValueError(f"{self.name}: {len(self.columns)} columns but align {self.align!r}")
        for row in self.rows:
            if len(row) != len(self.columns):
                raise ValueError(f"{self.name}: row {row} has {len(row)} cells")


def fmt_int(value) -> str:
    """12345.0 -> '12,345'; missing -> '–'."""
    if _missing(value):
        return "–"
    return f"{int(round(float(value))):,}"


def fmt_float(value, digits: int) -> str:
    """Fixed decimals; missing -> '–'."""
    if _missing(value):
        return "–"
    return f"{float(value):.{digits}f}"


def fmt_pct(value, digits: int = 1) -> str:
    """Share 0.2843 -> '28.4 %'; missing -> '–'."""
    if _missing(value):
        return "–"
    return f"{100 * float(value):.{digits}f} %"


def fmt_seconds(value) -> str:
    """Runtime with precision that suits its size: 0.20 s, 3.8 s, 482 s."""
    if _missing(value):
        return "–"
    v = float(value)
    if v < 1:
        return f"{v:.2f} s"
    if v < 100:
        return f"{v:.1f} s"
    return f"{v:,.0f} s"


def _missing(value) -> bool:
    if value is None or value == "":
        return True
    try:
        return math.isnan(float(value))
    except (TypeError, ValueError):
        return False


def latex_escape(text: str) -> str:
    """Escape LaTeX special characters in a cell or caption."""
    return "".join(_LATEX_ESCAPES.get(ch, ch) for ch in text)


def _md_cell(text: str) -> str:
    return text.replace("|", r"\|").replace("\n", " ")


def to_markdown(table: ReportTable) -> str:
    """GitHub-flavoured Markdown table with a provenance comment and notes."""
    sources = ", ".join(f"reports/tables/{s}" for s in table.sources)
    rule = {"l": ":---", "r": "---:", "c": ":---:"}
    lines = [
        f"<!-- Generated by `{GENERATED_BY}` from {sources}. Do not edit. -->",
        "",
        f"**{_md_cell(table.caption)}**",
        "",
        "| " + " | ".join(_md_cell(c) for c in table.columns) + " |",
        "|" + "|".join(rule[a] for a in table.align) + "|",
    ]
    lines += ["| " + " | ".join(_md_cell(c) for c in row) + " |" for row in table.rows]
    if table.notes:
        lines += ["", *[_md_cell(n) for n in table.notes]]
    return "\n".join(lines) + "\n"


def to_latex(table: ReportTable) -> str:
    """A booktabs `table` float with caption and label `tab:<name>`.

    Needs booktabs; artist names in non-Latin scripts need XeLaTeX or LuaLaTeX
    with a CJK-capable font (e.g. xeCJK).
    """
    sources = ", ".join(f"reports/tables/{s}" for s in table.sources)
    caption = " ".join([f"{table.caption}.", *table.notes]) if table.notes else table.caption
    lines = [
        f"% Generated by `{GENERATED_BY}` from {sources}. Do not edit.",
        "% Needs \\usepackage{booktabs}; compile with XeLaTeX or LuaLaTeX for non-Latin names.",
        r"\begin{table}[htbp]",
        r"\centering",
        r"\small",
        f"\\caption{{{latex_escape(caption)}}}",
        f"\\label{{tab:{table.name}}}",
        f"\\begin{{tabular}}{{{table.align}}}",
        r"\toprule",
        " & ".join(latex_escape(c) for c in table.columns) + r" \\",
        r"\midrule",
    ]
    lines += [" & ".join(latex_escape(c) for c in row) + r" \\" for row in table.rows]
    lines += [r"\bottomrule", r"\end{tabular}", r"\end{table}"]
    return "\n".join(lines) + "\n"


def write_table_files(table: ReportTable, out_dir: Path) -> list[Path]:
    """Write <name>.md and <name>.tex (UTF-8, LF) under out_dir; return both paths."""
    out_dir.mkdir(parents=True, exist_ok=True)
    paths = []
    for suffix, text in ((".md", to_markdown(table)), (".tex", to_latex(table))):
        path = out_dir / f"{table.name}{suffix}"
        path.write_text(text, encoding="utf-8", newline="\n")
        paths.append(path)
    return paths
